package main

import "strings"

// MoodScore — грубая оценка настроения по тексту ответа, от -2 до +2.
//
// ЧЕСТНО О ГРАНИЦАХ ЭТОГО РЕШЕНИЯ.
// Это словарь ключевых слов, а не анализ тональности. Он не поймёт
// ни отрицания («не очень хорошо»), ни сарказма, ни опечаток.
// Здесь он стоит на своём месте по двум причинам:
//
//  1. Оценка нужна ДЛЯ АГРЕГАТА по многим ответам одного человека,
//     где отдельные промахи усредняются, а не для решения о человеке.
//  2. Она считается СИНХРОННО в потребителе Kafka. Вызов внешнего LLM
//     на каждое сообщение сделал бы потребитель зависимым от чужого
//     API: недоступность OpenAI останавливала бы приём данных.
//     Умное толкование живёт в сервисе recommender, куда пользователь
//     приходит сам и где задержка допустима.
//
// Это типовой инженерный компромисс: дешёвое приближение в горячем пути,
// дорогое толкование — в холодном.
func MoodScore(text string) int8 {
	t := strings.ToLower(text)

	// Отрицание проверяется ПЕРВЫМ и переворачивает знак.
	// Без этого «не очень хорошо» получило бы +2 по слову «хорошо».
	// Полноценный разбор отрицаний словарём не сделать, но самый
	// частый случай закрыть дёшево — стоит.
	negated := strings.Contains(t, "не ") || strings.Contains(t, "нет ")

	score := int8(0)
	switch {
	case containsAny(t, "отлично", "прекрасно", "супер", "замечательно", "счастлив", "радост"):
		score = 2
	case containsAny(t, "хорошо", "неплохо", "бодр", "спокой", "норм"):
		score = 1
	case containsAny(t, "ужасно", "отврат", "депресс", "невыносим", "паник"):
		score = -2
	case containsAny(t, "плохо", "устал", "грустн", "тревож", "болит", "так себе"):
		score = -1
	}

	if negated && score != 0 {
		score = -score
	}
	return score
}

func containsAny(s string, subs ...string) bool {
	for _, sub := range subs {
		if strings.Contains(s, sub) {
			return true
		}
	}
	return false
}
